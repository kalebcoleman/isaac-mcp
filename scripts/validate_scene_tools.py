"""Live MCP-path smoke test. Mutates ONLY the explicitly selected disposable stage.

Requires approved root 'fixture' generated by make_scene_fixture.py and a stopped
fresh Sim. Records actual tool results; never uses run_python or bridge APIs.
"""

import argparse
import asyncio
import json
from pathlib import Path
import time
from scene_mcp_client import parameters, call
from mcp import ClientSession
from mcp.client.stdio import stdio_client


async def validate(port, output):
    transcript = []
    async with stdio_client(parameters(port)) as (r, w):
        async with ClientSession(r, w) as c:
            await c.initialize()
            listed = await c.list_tools()
            assert (
                len([t for t in listed.tools if t.name.startswith("ur5e_dt__")]) == 23
            )

            async def invoke(name, args=None, expect_error=False):
                item = await call(c, name, args or {})
                transcript.append(item)
                Path(output).write_text(json.dumps(transcript, indent=2))
                assert item["isError"] == expect_error, item
                return item["result"]

            info = await invoke("sim__stage__info")
            for _ in range(120):
                if info.get("app_ready", True):
                    break
                await asyncio.sleep(1)
                info = await invoke("sim__stage__info")
            assert info.get("app_ready", True), info
            target = {k: info[k] for k in ("session_id", "stage_id")}
            assert info["stopped"]
            await invoke("assets__roots")
            await invoke("assets__scan", {"root_id": "fixture"})
            await invoke("assets__scan", {"root_id": "not-approved"}, True)
            tree = await invoke("sim__stage__tree", target)
            if not any(p["path"] == "/World" for p in tree["nodes"]):
                await invoke(
                    "sim__prim__create", dict(**target, path="/World", kind="Xform")
                )
            await invoke("sim__prim__get", dict(**target, path="/World/Absent"), True)
            await invoke(
                "sim__prim__create",
                dict(
                    **target,
                    path="/World/Parent",
                    kind="Xform",
                    position=[1, 0, 0],
                    orientation=[2**-0.5, 0, 0, 2**-0.5],
                ),
            )
            asset = dict(**target, root_id="fixture", relative_path="robot.usda")
            await invoke("assets__info", asset)
            await invoke(
                "assets__import_usd",
                dict(
                    **asset,
                    prim_path="/World/Parent/Robot",
                    position=[0, 0, 0],
                    frame="world",
                ),
            )
            await invoke(
                "assets__import_usd",
                dict(**asset, prim_path="/World/Parent/Robot"),
                True,
            )
            await invoke(
                "sim__prim__set_transform",
                dict(
                    **target,
                    path="/World/Parent/Robot",
                    position=[0.5, 0, 0],
                    frame="world",
                ),
            )
            prim = await invoke(
                "sim__prim__get", dict(**target, path="/World/Parent/Robot")
            )
            assert all(
                abs(a - b) < 1e-6 for a, b in zip(prim["world_position"], [0.5, 0, 0])
            )
            physics = await invoke(
                "sim__physics__inspect", dict(**target, root="/World/Parent/Robot")
            )
            assert any(p["articulation_root"] for p in physics["nodes"])
            assert any(p["joint"] for p in physics["nodes"])
            await invoke("sim__prim__find", dict(**target, contains="Robot"))
            small = await invoke("sim__stage__tree", dict(**target, limit=1))
            assert small["truncated"]
            await invoke(
                "sim__viewport__frame", dict(**target, path="/World/Parent/Robot")
            )
            await invoke(
                "sim__prim__create",
                dict(**target, path="/World/Physics", kind="PhysicsScene"),
            )
            await invoke(
                "sim__prim__create",
                dict(
                    **target,
                    path="/World/Falling",
                    kind="Cube",
                    size=0.2,
                    position=[2, 0, 3],
                    rigid=True,
                ),
            )
            before = await invoke(
                "sim__prim__get", dict(**target, path="/World/Falling")
            )
            await invoke("sim__timeline__control", dict(**target, action="play"))
            await invoke(
                "sim__prim__set_transform", dict(**target, path="/World/Falling"), True
            )
            before = await invoke(
                "sim__body__state",
                dict(**target, path="/World/Falling", include_dynamics=True),
            )
            await asyncio.sleep(0.6)
            await invoke("sim__timeline__control", dict(**target, action="pause"))
            after = await invoke(
                "sim__body__state",
                dict(**target, path="/World/Falling", include_dynamics=True),
            )
            assert after["world_position"][2] < before["world_position"][2] - 0.05, (
                before,
                after,
            )
            rendered = await invoke(
                "sim__prim__get", dict(**target, path="/World/Falling")
            )
            assert after["dynamics"]["mass_kg"] > 0
            assert (
                after["dynamics"]["linear_velocity"][2]
                < before["dynamics"]["linear_velocity"][2]
            )
            if after["backend"] == "physx":
                assert all(
                    abs(a - b) < 1e-5
                    for a, b in zip(rendered["world_position"], after["world_position"])
                ), (rendered, after)
            else:
                assert rendered["world_position"] == [2, 0, 3], rendered
            await invoke(
                "sim__stage__save",
                dict(**target, filename="paused-" + str(time.time_ns()) + ".usda"),
            )
            await invoke("sim__timeline__control", dict(**target, action="stop"))
            await invoke(
                "sim__stage__save",
                dict(**target, filename="smoke-" + str(time.time_ns()) + ".usda"),
            )
            await invoke(
                "sim__stage__save", dict(**target, filename="../bad.usda"), True
            )
            await invoke(
                "sim__prim__create",
                dict(**target, path="/World/Bad", kind="ScriptNode"),
                True,
            )
            await invoke(
                "sim__prim__get",
                dict(**{**target, "stage_id": "stale"}, path="/World"),
                True,
            )
    print(
        json.dumps(
            dict(
                passed=True,
                calls=len(transcript),
                pid=info["pid"],
                port=port,
                gravity_before=before["world_position"],
                gravity_after=after["world_position"],
                backend=after["backend"],
                observation=after["source"],
            )
        )
    )


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--port", type=int, required=True)
    p.add_argument("--output", required=True)
    a = p.parse_args()
    asyncio.run(validate(a.port, a.output))
