#!/usr/bin/env python3
"""Generate docs/TOOLS-ARGUMENTS.md: every MCP tool with its arguments, from the code.

Catalogued tools come from the packaged snapshots (``mcp/isaac_mcp/catalogs/*.json``); host tools
come from their function signatures, read with ``ast`` so this needs no dependencies, no bridge
and no simulator. ``scripts/check_docs.py`` fails when the page has drifted.

    python3 scripts/gen_tool_reference.py --write   # regenerate the page
    python3 scripts/gen_tool_reference.py --check   # exit 1 when it has drifted (default)
"""

import argparse
import ast
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "mcp"))
from isaac_mcp import tool_groups  # noqa: E402 - stdlib-only data
OUTPUT = ROOT / "docs" / "TOOLS-ARGUMENTS.md"
CATALOGS = ROOT / "mcp" / "isaac_mcp" / "catalogs"
HEADER = """# Tool arguments

**Generated by `scripts/gen_tool_reference.py`; do not edit by hand.** Every tool the server
registers, with its arguments, taken from the code. Use it to look up a name, a default or what is
required. For behavior, refusals and limits, read the page linked in each section.

A client is shown most of these as an action of a [grouped tool](TOOLS-HOST.md#grouped-tools): each
such entry says "Listed as", and takes the same arguments either way. The single-purpose name still
works when called if its toolset is enabled. Disabled toolsets register no tools.

Arguments are shown as `name` (type, required) or `name` (type, default). Generic scene tools refuse
arguments they do not declare, so a misspelled name is an error rather than being ignored. A live
bridge's own metadata takes precedence over these snapshots once discovered.
"""
LOCAL_SECTIONS = (
    ("Host gateway and desktop", "TOOLS-HOST.md",
     ("server.py", "screen.py")),
    ("Desktop input (opt-in: `input` toolset)", "TOOLS-HOST.md#optional-desktop-input",
     ("desktop_input.py",)),
    ("Simulator sessions (opt-in: `launch` toolset)", "TOOLS-HOST.md#optional-simulator-sessions",
     ("sim_sessions.py",)),
    ("Isaac Lab", "TOOLS-ISAACLAB.md", ("isaaclab/tools.py",)),
    ("RoboSimStudio (opt-in: `robosim` toolset)", "ROBOSIM.md", ("robosim/tools.py",)),
)
CATALOG_SECTIONS = (
    ("Bridge built-ins", "TOOLS-HOST.md#kit-bridge-built-ins", "builtins.json"),
    ("Generic scene (`sim__*`)", "TOOLS-SCENE.md", "sim.json"),
    ("Assets (`assets__*`)", "TOOLS-SCENE.md", "assets.json"),
    ("UR5e twin (`ur5e_dt__*`)", "TOOLS-UR5E.md", "ur5e_dt.json"),
)


def one_line(text):
    return " ".join((text or "").split())


def annotated_parts(annotation, aliases):
    """Return (type source, description) of a signature annotation, seeing through Annotated.

    The module-level alias form (``_WindowId = Annotated[...]``) counts as well. Only the source is
    read, so this stays free of pydantic and of the SDK.
    """
    if isinstance(annotation, ast.Name) and annotation.id in aliases:
        annotation = aliases[annotation.id]
    if not (isinstance(annotation, ast.Subscript) and isinstance(annotation.value, ast.Name)
            and annotation.value.id == "Annotated" and isinstance(annotation.slice, ast.Tuple)):
        return ast.unparse(annotation), ""
    base, *metadata = annotation.slice.elts
    for item in metadata:
        if isinstance(item, ast.Call) and getattr(item.func, "id", "") == "Field":
            for keyword in item.keywords:
                if keyword.arg == "description" and isinstance(keyword.value, ast.Constant):
                    return ast.unparse(base), keyword.value.value
    return ast.unparse(base), ""


def local_tools(path):
    """Return {tool name: (description, [(arg, type, required, default, detail)])} for one host module."""
    tools = {}
    tree = ast.parse(path.read_text())
    aliases = {target.id: node.value for node in tree.body if isinstance(node, ast.Assign)
               and isinstance(node.value, ast.Subscript)
               for target in node.targets if isinstance(target, ast.Name)}
    # A default such as DEFAULT_MAX_WIDTH reads better, and matches the MCP schema, as its value.
    constants = {target.id: node.value for node in tree.body if isinstance(node, ast.Assign)
                 and isinstance(node.value, ast.Constant)
                 for target in node.targets if isinstance(target, ast.Name)}
    for node in ast.walk(tree):
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        decorators = [d for d in node.decorator_list if isinstance(d, ast.Call)
                      and isinstance(d.func, ast.Attribute) and d.func.attr == "tool"]
        if not decorators:
            continue
        name = next((kw.value.value for kw in decorators[0].keywords
                     if kw.arg == "name" and isinstance(kw.value, ast.Constant)), node.name)
        positional = node.args.posonlyargs + node.args.args
        defaults = [None] * (len(positional) - len(node.args.defaults)) + list(node.args.defaults)
        arguments = []
        for arg, default in zip(positional + node.args.kwonlyargs,
                                defaults + list(node.args.kw_defaults)):
            if arg.arg in ("self", "ctx"):
                continue
            kind, detail = annotated_parts(arg.annotation, aliases) if arg.annotation is not None else ("any", "")
            if isinstance(default, ast.Name):
                default = constants.get(default.id, default)
            arguments.append((arg.arg, kind, default is None,
                              None if default is None else ast.unparse(default), one_line(detail)))
        doc = ast.get_docstring(node) or ""
        tools[name] = (one_line(doc.split("\n\n", 1)[0]), arguments)
    return tools


def catalog_tools(path):
    tools = {}
    for name, entry in json.loads(path.read_text())["tools"].items():
        arguments = []
        for field in entry.get("fields", []):
            kind = "|".join(field["enum"]) if field.get("enum") else field.get("kind", "any")
            default = json.dumps(field.get("default")) if field.get("has_default") else None
            arguments.append((field["name"], kind, bool(field.get("required")), default,
                              one_line(field.get("description"))))
        tools[name.replace(".", "__")] = (one_line(entry.get("description")), arguments)
    return tools


def render_tool(name, description, arguments):
    lines = [f"### `{name}`", ""]
    listed_as = tool_groups.replacement(name)
    if listed_as:
        lines += [f"Listed as `{listed_as}`.", ""]
    if description:
        lines += [description, ""]
    if not arguments:
        lines += ["No arguments.", ""]
        return lines
    for argument in arguments:
        arg, kind, required, default = argument[:4]
        detail = argument[4] if len(argument) > 4 else ""
        state = "required" if required else ("optional" if default is None else f"default `{default}`")
        lines.append(f"- `{arg}` ({kind}, {state})" + (f": {detail}" if detail else ""))
    lines.append("")
    return lines


def render():
    lines = [HEADER]
    sections = []
    for title, link, modules in LOCAL_SECTIONS:
        tools = {}
        for module in modules:
            tools.update(local_tools(ROOT / "mcp" / "isaac_mcp" / module))
        sections.append((title, link, tools))
    for title, link, filename in CATALOG_SECTIONS:
        sections.append((title, link, catalog_tools(CATALOGS / filename)))
    for title, link, tools in sections:
        lines += [f"## {title}", "", f"Reference: [{link.split('#')[0]}]({link}). {len(tools)} tools.", ""]
        for name in sorted(tools):
            lines += render_tool(name, *tools[name])
    return "\n".join(lines).rstrip() + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--write", action="store_true", help="regenerate the page")
    group.add_argument("--check", action="store_true", help="exit 1 when the page has drifted")
    args = parser.parse_args()
    text = render()
    if args.write:
        OUTPUT.write_text(text)
        print(f"wrote {OUTPUT.relative_to(ROOT)}")
        return 0
    if not OUTPUT.is_file() or OUTPUT.read_text() != text:
        print(f"{OUTPUT.relative_to(ROOT)} is stale: run python3 scripts/gen_tool_reference.py --write")
        return 1
    print(f"{OUTPUT.relative_to(ROOT)} is current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
